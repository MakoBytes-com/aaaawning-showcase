#!/usr/bin/env node
// Walks public/images/ and writes lib/images-manifest.ts with per-category
// file lists so components can import them without hitting the filesystem
// at request time.
//
// Run whenever images are added/removed:
//   node scripts/build-image-manifest.mjs

import { readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve("public/images");

const IMG_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
const VIDEO_EXT = new Set([".mp4", ".webm", ".mov"]);

async function listImages(dir) {
  try {
    const entries = await readdir(dir);
    const out = [];
    for (const name of entries) {
      const full = path.join(dir, name);
      const s = await stat(full);
      if (!s.isFile()) continue;
      const ext = path.extname(name).toLowerCase();
      if (IMG_EXT.has(ext) || VIDEO_EXT.has(ext)) out.push(name);
    }
    return out.sort();
  } catch {
    return [];
  }
}

async function main() {
  const categoryDirs = (await readdir(ROOT, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const manifest = {};
  for (const cat of categoryDirs) {
    const files = await listImages(path.join(ROOT, cat));
    manifest[cat] = files.map((f) => `/images/${cat}/${f}`);
  }

  const ts = `// AUTO-GENERATED by scripts/build-image-manifest.mjs — do not edit by hand.
// Re-run the script whenever files in public/images/ change.

export const IMAGES = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageCategory = keyof typeof IMAGES;

export function getImages(category: string): readonly string[] {
  return (IMAGES as Record<string, readonly string[]>)[category] ?? [];
}
`;

  await writeFile(path.join("lib", "images-manifest.ts"), ts, "utf8");

  const totals = Object.entries(manifest)
    .map(([k, v]) => `  ${k.padEnd(20)} ${v.length}`)
    .join("\n");
  console.log("Wrote lib/images-manifest.ts\n" + totals);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
